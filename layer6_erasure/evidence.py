"""Layer 6 evidence run (read-only: it reuses the evaluator unchanged).      python -m layer6_erasure.evidence
 A. FRESH SEEDS: stores seeded with random seeds the agent was never developed on (101, 202, 303, 404), each against both request sets (10 'public' + 20 'heldout' = 30 requests,
    ~170-850 seeded copies per run): completeness, copies left silently, collateral damage, status, passes, time.
 B. SCALE: the same, with the stores made 1x / 4x / 20x / 60x bigger (50 -> 3000 borrowers), to see how erasure time grows against the 15-minute (900 s) limit.
Writes layer6_erasure/EVIDENCE.md.  ALL stores are MOCKS generated by our own seeder: this shows the agent is not overfitted to one seed and how its time grows. It does NOT show it works on the
organisers' real store layouts (not available to us)."""
import collections
import json
import os
import shutil
import statistics
import sys
import tempfile
import time
import warnings

os.environ.setdefault("VAULT_ALLOW_EPHEMERAL", "1")
warnings.filterwarnings("ignore")
import layer6_erasure.evaluate as ev
from layer6_erasure import mock_data

q = lambda xs, f: sorted(xs)[min(len(xs) - 1, int(f * len(xs)))] if xs else float("nan")


def one(seed, n, which):
    d = tempfile.mkdtemp(); ev.PRISTINE, ev.WORK = f"{d}/pristine", f"{d}/work"
    try:
        t0 = time.time(); truth = mock_data.seed(ev.PRISTINE, n=n, seed_=seed); t_seed = time.time() - t0
        recs = sum(1 for dp, _, fs in os.walk(ev.PRISTINE) for f in fs if f.endswith(".jsonl") for _ in open(os.path.join(dp, f), encoding="utf-8"))
        t0 = time.time(); res, s = ev.run(which, verbose=False); wall = time.time() - t0
        durs = [r["duration_s"] for r in res]
        return {"seed": seed, "n": n, "which": which, "records": recs, "requests": s["requests"], "seeded": s["seeded_copies"], "removed": s["removed"], "pct": s["completeness_pct"], "statuses": s["statuses"],
                "silent": s["survivors_SILENT"], "flagged": s["survivors_flagged_for_human"], "collateral": s["collateral_total"], "max_passes": s["max_passes"], "chain": s["chain"][0],
                "p50": statistics.median(durs), "p95": q(durs, .95), "max": max(durs), "wall": wall, "seed_s": t_seed, "kinds": s["survivor_kinds"]}
    finally:
        shutil.rmtree(d, ignore_errors=True)


def main():
    L = ["# Layer 6 erasure: evidence on fresh seeds and at scale", "", "MOCK stores generated by our own seeder (the organisers' real layout is not available). Fresh random seeds the agent was never developed on. "
         "'completeness' = seeded copies removed; 'silent' = copies left behind that the agent did NOT flag for a human; 'collateral' = other borrowers' or decoy records deleted by mistake. Limit: 15 minutes (900 s) per erasure request.", "",
         "## A. Fresh seeds (n = 50 borrowers), both request sets", "", "| seed | request set | requests | seeded copies | removed | completeness | statuses | silent | flagged for human | collateral | max passes | slowest request | audit chain |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    tot = {"seeded": 0, "removed": 0, "silent": 0, "collateral": 0, "reqs": 0}
    for seed in (101, 202, 303, 404):
        for which in ("public", "heldout"):
            r = one(seed, 50, which); print("A", seed, which, r["pct"], r["silent"], r["collateral"], round(r["max"], 2), flush=True)
            L.append(f"| {seed} | {which} | {r['requests']} | {r['seeded']} | {r['removed']} | {r['pct']}% | {r['statuses']} | {r['silent']} | {r['flagged']} | {r['collateral']} | {r['max_passes']} | {r['max']:.2f} s | {'intact' if r['chain'] else 'BROKEN'} |")
            tot["seeded"] += r["seeded"]; tot["removed"] += r["removed"]; tot["silent"] += r["silent"]; tot["collateral"] += r["collateral"]; tot["reqs"] += r["requests"]
    L += ["", f"**Totals on fresh seeds:** {tot['reqs']} erasure requests, {tot['seeded']} seeded copies, {tot['removed']} removed ({100 * tot['removed'] / tot['seeded']:.1f}%), {tot['silent']} left silently, {tot['collateral']} collateral deletions.", "",
          "## B. Scale: how erasure time grows with store size (seed 505, heldout request set)", "", "| borrowers | records in all stores | seeded copies | completeness | silent | collateral | request time p50 | p95 | slowest | vs 900 s limit |", "|---|---|---|---|---|---|---|---|---|---|"]
    for n in (50, 200, 1000, 3000):
        r = one(505, n, "heldout"); print("B", n, r["records"], round(r["p50"], 2), round(r["max"], 2), flush=True)
        L.append(f"| {n} | {r['records']:,} | {r['seeded']} | {r['pct']}% | {r['silent']} | {r['collateral']} | {r['p50']:.2f} s | {r['p95']:.2f} s | {r['max']:.2f} s | {100 * r['max'] / 900:.2f}% of the limit |")
    L += ["", "Caveats: mock stores only; one machine; stores are local JSONL files (real stores add network latency per call); times are the agent's own `duration_s` per request; the seeder and the agent were written by the same people."]
    open(os.path.join(os.path.dirname(__file__), "EVIDENCE.md"), "w").write("\n".join(L)); print("wrote EVIDENCE.md")


if __name__ == "__main__":
    main()
